#!/usr/bin/env python3
"""
IoT Data Simulator - Portainer Automated Deployment CLI
======================================================
Automation script to trigger deployment or continuous rolling updates
of the IoT Data Simulator stack on a Portainer instance (local, edge, or remote).

Supported deployment modes:
1. Portainer Stack Webhook Trigger (local private LAN or public URL):
   python3 scripts/portainer_deploy.py --webhook "http://<PORTAINER_HOST>:9000/api/stacks/webhooks/xxxx"

2. Portainer REST API Automation (using API access token):
   python3 scripts/portainer_deploy.py --url "http://<PORTAINER_HOST>:9000" --api-key "ptr_xxx" --stack "iot-simulator" --pull

3. Automated configuration detection via local environment file (.env.portainer):
   python3 scripts/portainer_deploy.py
"""

import argparse
import json
import os
import sys
import ssl
from pathlib import Path
from typing import Dict, Any, Optional
import urllib.request
import urllib.error


def load_env_file(env_path: Path) -> Dict[str, str]:
    """Loads a key-value .env file without external dependencies.

    Args:
        env_path: Path to the .env formatted configuration file.

    Returns:
        Dictionary of parsed environment variables.
    """
    env_vars = {}
    if not env_path.exists():
        return env_vars
    try:
        with open(env_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                if "=" in line:
                    key, val = line.split("=", 1)
                    key = key.strip()
                    val = val.strip().strip("'\"")
                    env_vars[key] = val
    except Exception as e:
        print(f"⚠️ Warning: unable to parse {env_path}: {e}")
    return env_vars


def make_request(
    url: str,
    method: str = "GET",
    headers: Optional[Dict[str, str]] = None,
    data: Optional[Dict[str, Any]] = None,
    insecure: bool = False,
    timeout: int = 30
) -> Dict[str, Any]:
    """Executes an HTTP/HTTPS network request using the Python standard library.

    Args:
        url: Complete target URL.
        method: HTTP verb (GET, POST, PUT, DELETE).
        headers: Optional dictionary of HTTP request headers.
        data: Optional payload dictionary to be serialized as JSON.
        insecure: If True, bypasses SSL/TLS certificate verification.
        timeout: Socket timeout in seconds.

    Returns:
        Dictionary containing success boolean, status_code, parsed data, and errors.
    """
    req_headers = headers.copy() if headers else {}
    body = None

    if data is not None:
        body = json.dumps(data).encode("utf-8")
        if "Content-Type" not in req_headers:
            req_headers["Content-Type"] = "application/json"

    req = urllib.request.Request(url, data=body, headers=req_headers, method=method)

    context = None
    if insecure and url.startswith("https://"):
        context = ssl._create_unverified_context()

    try:
        with urllib.request.urlopen(req, timeout=timeout, context=context) as response:
            status_code = response.getcode()
            raw_body = response.read().decode("utf-8", errors="replace")
            parsed_data = None
            if raw_body:
                try:
                    parsed_data = json.loads(raw_body)
                except json.JSONDecodeError:
                    parsed_data = raw_body
            return {
                "success": 200 <= status_code < 300,
                "status_code": status_code,
                "data": parsed_data,
                "raw": raw_body,
            }
    except urllib.error.HTTPError as e:
        err_body = e.read().decode("utf-8", errors="replace") if hasattr(e, "read") else ""
        return {
            "success": False,
            "status_code": e.code,
            "data": err_body,
            "raw": err_body,
            "error": str(e)
        }
    except Exception as e:
        return {
            "success": False,
            "status_code": 0,
            "data": None,
            "raw": "",
            "error": str(e)
        }


def trigger_webhook(webhook_url: str, insecure: bool = False) -> bool:
    """Triggers Portainer automated stack redeployment via its Webhook URL.

    Args:
        webhook_url: Stack webhook endpoint generated by Portainer.
        insecure: If True, skips TLS certificate verification.

    Returns:
        True if Portainer acknowledged the redeployment hook, False otherwise.
    """
    print(f"🚀 Triggering Portainer Webhook: {webhook_url}")
    res = make_request(webhook_url, method="POST", insecure=insecure)
    if res["success"]:
        print(f"✅ Success! Portainer acknowledged the webhook trigger (HTTP: {res['status_code']}).")
        print("📦 Portainer is pulling the latest GHCR image and recreating containers.")
        return True
    else:
        print(f"❌ Webhook call failed (HTTP: {res['status_code']})")
        if res.get("error"):
            print(f"   Details: {res['error']}")
        if res.get("data"):
            print(f"   Response: {res['data']}")
        return False


def redeploy_via_api(
    base_url: str,
    api_key: str,
    stack_name: str,
    endpoint_id: Optional[int] = None,
    pull_image: bool = True,
    insecure: bool = False
) -> bool:
    """Redeploys and updates a stack via the official Portainer REST API.

    Args:
        base_url: Base Portainer server URL.
        api_key: Portainer API authentication token.
        stack_name: Target stack name.
        endpoint_id: Optional Docker environment ID; auto-detected if None.
        pull_image: Whether to pull the latest Docker image before re-creation.
        insecure: If True, skips TLS certificate validation.

    Returns:
        True if the redeployment succeeded, False otherwise.
    """
    base_url = base_url.rstrip("/")
    headers = {
        "X-API-Key": api_key,
        "Accept": "application/json"
    }

    print(f"🔍 Connecting to Portainer REST API at {base_url}...")

    # 1. Resolve endpoint ID if not provided
    if endpoint_id is None:
        print("📋 Resolving primary Docker environment (Endpoint)...")
        res_ep = make_request(f"{base_url}/api/endpoints", headers=headers, insecure=insecure)
        if not res_ep["success"]:
            print(f"❌ Unable to list Portainer endpoints (Code: {res_ep['status_code']})")
            print(f"   Error: {res_ep.get('error') or res_ep.get('data')}")
            return False
        
        endpoints = res_ep["data"]
        if not isinstance(endpoints, list) or len(endpoints) == 0:
            print("❌ No Docker environment found in this Portainer instance.")
            return False
        
        endpoint_id = endpoints[0]["Id"]
        print(f"ℹ️ Selected default environment: ID {endpoint_id} ({endpoints[0].get('Name', 'Local')})")

    # 2. Search target stack by name
    print(f"🔎 Searching for stack '{stack_name}' in environment {endpoint_id}...")
    res_stacks = make_request(f"{base_url}/api/stacks", headers=headers, insecure=insecure)
    if not res_stacks["success"]:
        print(f"❌ Unable to list Portainer stacks (Code: {res_stacks['status_code']})")
        return False

    target_stack = None
    for st in res_stacks["data"]:
        if st.get("Name") == stack_name:
            target_stack = st
            break

    if not target_stack:
        print(f"❌ Stack '{stack_name}' not found in Portainer.")
        print("   Available stacks: " + ", ".join([s.get("Name", "unnamed") for s in res_stacks["data"]]))
        return False

    stack_id = target_stack["Id"]
    stack_type = target_stack.get("Type")
    is_git = bool(target_stack.get("GitConfig"))
    print(f"✅ Target stack identified: ID {stack_id} (Type: {stack_type}, Git Stack: {is_git})")

    # 3. Trigger redeployment
    if is_git:
        # Stack deployed from Git: call /git/redeploy
        redeploy_url = f"{base_url}/api/stacks/{stack_id}/git/redeploy?endpointId={endpoint_id}"
        payload = {
            "prune": True,
            "pullImage": pull_image
        }
        print(f"🚀 Triggering Git redeployment (pullImage={pull_image}, prune=True)...")
        res_dep = make_request(redeploy_url, method="PUT", headers=headers, data=payload, insecure=insecure, timeout=120)
    else:
        # Standard stack: update stack
        redeploy_url = f"{base_url}/api/stacks/{stack_id}?endpointId={endpoint_id}"
        payload = {
            "id": stack_id,
            "prune": True,
            "pullImage": pull_image
        }
        print("🚀 Updating and redeploying standard stack...")
        res_dep = make_request(redeploy_url, method="PUT", headers=headers, data=payload, insecure=insecure, timeout=120)

    if res_dep["success"]:
        print("✅ Portainer deployment completed successfully!")
        print(f"ℹ️ Stack '{stack_name}' has been refreshed with the latest image.")
        return True
    else:
        print(f"❌ Error during stack redeployment (HTTP: {res_dep['status_code']})")
        print(f"   Details: {res_dep.get('error') or res_dep.get('data')}")
        return False


def main():
    """CLI entrypoint for automated Portainer stack deployment."""
    parser = argparse.ArgumentParser(
        description="Automated deployment and rolling update CLI for IoT Data Simulator on Portainer."
    )
    parser.add_argument("--webhook", help="Portainer Stack Webhook URL")
    parser.add_argument("--url", help="Base URL of Portainer (e.g., http://<PORTAINER_HOST>:9000 or https://portainer.example.com:9443)")
    parser.add_argument("--api-key", help="Portainer API Access Token (X-API-Key generated in User Profile > Access Tokens)")
    parser.add_argument("--stack", default="iot-simulator", help="Target Portainer stack name (default: iot-simulator)")
    parser.add_argument("--endpoint-id", type=int, help="Docker environment ID in Portainer (default: auto-detected)")
    parser.add_argument("--no-pull", action="store_true", help="Do not force pulling the latest Docker image")
    parser.add_argument("--insecure", "-k", action="store_true", help="Ignore SSL/TLS certificate errors for self-signed certificates")
    parser.add_argument("--env-file", default=".env.portainer", help="Local configuration file (default: .env.portainer)")

    args = parser.parse_args()

    # Load local configuration file if present
    project_root = Path(__file__).resolve().parent.parent
    env_file_path = project_root / args.env_file
    file_vars = load_env_file(env_file_path)

    webhook_url = args.webhook or file_vars.get("PORTAINER_WEBHOOK_URL") or os.environ.get("PORTAINER_WEBHOOK_URL")
    portainer_url = args.url or file_vars.get("PORTAINER_URL") or os.environ.get("PORTAINER_URL")
    api_key = args.api_key or file_vars.get("PORTAINER_API_KEY") or os.environ.get("PORTAINER_API_KEY")
    stack_name = args.stack or file_vars.get("PORTAINER_STACK_NAME") or os.environ.get("PORTAINER_STACK_NAME") or "iot-simulator"
    endpoint_id = args.endpoint_id
    if endpoint_id is None and "PORTAINER_ENDPOINT_ID" in file_vars:
        try:
            endpoint_id = int(file_vars["PORTAINER_ENDPOINT_ID"])
        except ValueError:
            pass

    # Interactive prompt fallback if running in a terminal without parameters
    if not webhook_url and not (portainer_url and api_key):
        if sys.stdin.isatty():
            print("\n🚀 Aucun paramètre de déploiement Portainer détecté. Mode interactif :")
            print("1. Déclenchement par Webhook de stack Portainer")
            print("2. Déclenchement par API REST Portainer (Token d'accès)")
            print("Q. Quitter")
            try:
                choice = input("\nChoisissez une option [1/2/Q] : ").strip()
            except (EOFError, KeyboardInterrupt):
                print("\nAnnulé par l'utilisateur.")
                sys.exit(1)

            if choice == "1":
                try:
                    webhook_url = input("Entrez l'URL du Webhook Portainer : ").strip()
                except (EOFError, KeyboardInterrupt):
                    sys.exit(1)
            elif choice == "2":
                try:
                    portainer_url = input("Entrez l'URL de Portainer (ex: http://192.168.1.100:9000) : ").strip()
                    api_key = input("Entrez la clé d'API Portainer (X-API-Key) : ").strip()
                    custom_stack = input(f"Nom de la stack Portainer [{stack_name}] : ").strip()
                    if custom_stack:
                        stack_name = custom_stack
                except (EOFError, KeyboardInterrupt):
                    sys.exit(1)
            else:
                print("Annulation.")
                sys.exit(0)

    # Option 1: Trigger via Webhook
    if webhook_url:
        success = trigger_webhook(webhook_url, insecure=args.insecure)
        sys.exit(0 if success else 1)

    # Option 2: Trigger via REST API
    if portainer_url and api_key:
        success = redeploy_via_api(
            base_url=portainer_url,
            api_key=api_key,
            stack_name=stack_name,
            endpoint_id=endpoint_id,
            pull_image=not args.no_pull,
            insecure=args.insecure
        )
        sys.exit(0 if success else 1)

    # Fallback when no parameters were supplied
    print("❌ No Portainer deployment parameters detected.")
    print("\n💡 Instructions to configure automated deployment:")
    print("   1. Option A (Local Stack Webhook):")
    print("      python3 scripts/portainer_deploy.py --webhook 'http://<PORTAINER_HOST>:9000/api/stacks/webhooks/<TOKEN>'")
    print("\n   2. Option B (Portainer REST API):")
    print("      python3 scripts/portainer_deploy.py --url 'http://<PORTAINER_HOST>:9000' --api-key 'ptr_xxx'")
    print("\n   3. Option C (Configuration file):")
    print("      Create a '.env.portainer' file based on '.env.portainer.example'.")
    print("\n   Refer to 'Documentation/devops/portainer_deployment.md' for complete setup details.")
    sys.exit(1)


if __name__ == "__main__":
    main()
